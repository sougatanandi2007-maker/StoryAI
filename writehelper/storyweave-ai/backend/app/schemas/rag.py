"""
StoryWeave AI - RAG and AI Chat Schemas

Pydantic validation schemas for story universe query retrieval, context assembly,
and grounded Gemini response generation.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Payload for submitting a universe query to the AI writing assistant."""

    story_id: str = Field(
        ...,
        min_length=1,
        description="Target story universe ID whose memories will be searched.",
    )
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The author's question or instruction about their story universe.",
    )
    top_k: Optional[int] = Field(
        default=5,
        ge=1,
        le=20,
        description="Maximum number of relevant memory chunks to retrieve.",
    )
    min_relevance: Optional[float] = Field(
        default=0.25,
        ge=0.0,
        le=1.0,
        description="Minimum cosine similarity threshold (0.0 to 1.0) required to include a memory chunk.",
    )


class ChatSourceReference(BaseModel):
    """Source attribution for a memory chunk utilized in constructing the answer."""

    chapter_id: str = Field(..., description="ID of the source chapter")
    chapter_number: int = Field(..., description="Chapter sequence number")
    chunk_id: str = Field(..., description="Unique deterministic chunk ID")
    memory_type: str = Field(..., description="Memory classification (e.g. manuscript_chunk)")
    relevant_excerpt: str = Field(..., description="Text excerpt from the manuscript chunk")
    similarity_score: float = Field(
        ...,
        description="Calculated cosine similarity score between query and chunk (0.0 to 1.0, higher is more similar)",
    )
    distance: float = Field(
        ...,
        description="Raw vector distance metric from ChromaDB (lower indicates closer vector proximity)",
    )


class ChatResponse(BaseModel):
    """Structured response returned by the RAG pipeline."""

    answer: str = Field(..., description="Grounded answer generated by Gemini AI")
    story_id: str = Field(..., description="Story universe ID")
    sources: List[ChatSourceReference] = Field(
        default_factory=list,
        description="List of source memory references used to ground the answer",
    )
    retrieval_count: int = Field(
        ...,
        description="Number of relevant memory chunks retrieved above the threshold",
    )
    insufficient_context: bool = Field(
        default=False,
        description="True if the retrieved story memory was insufficient to answer the question reliably",
    )
    model_used: Optional[str] = Field(
        default=None,
        description="Gemini model identifier utilized for generation",
    )
    processing_time_ms: Optional[float] = Field(
        default=None,
        description="Total round-trip pipeline latency in milliseconds",
    )
